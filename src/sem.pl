all_modules(Modules) :-
    aggregate_all(set(M), (
        instr_info(_, Info),
        [M] = Info.module
    ), Modules).

module_instrs(Module, Instrs) :-
    bagof(I, instr_module(I, Module), Instrs).

instr_module(Instr, Module) :-
    instr_info(Instr, Info),
    [Module] = Info.module.


