mod_def(subtr{
    x: in, y: in,
    diff: out, signin: out(1), carryout: out(1)
}, (
    adder{
        x: ?x, y: ~(?y), carryin: #1,
        sum: ?diff, signin: ?signin, carryout: ?carryout
    }
)).

mod_def(lessthan{
    x: in, y: in, lessthan: out(1)
}, (
    subtr{
        x: ?x, y: ?y,
        diff: ?diff, signin: ?sin, carryout: ?cout
    };
    % "Internally, the overflow flag is usually generated by an exclusive or
    % of the internal carry into and out of the sign bit."
    ?overflow := ?sin xor ?cout;
    % "If the exclusive-or of the sign and overflow flags is 1, the
    % subtraction result was less than zero, otherwise the result was zero
    % or greater."
    ?sign := bit(?diff, #15);
    ?lessthan := ?overflow xor ?sign
)).

mod_def(b_push{ stack_in: in(N), stack_out: out(N), bit: in(1) },
    ?stack_out := (?stack_in << #1) and zxt(?bit)
).
%mod_def(b_push{ bit: in(1) },
